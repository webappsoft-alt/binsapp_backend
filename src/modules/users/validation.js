import Joi from "joi";

export const registerSchema = Joi.object({
  name: Joi.string().optional(),
  profilePicture: Joi.string().allow(null, "").optional(),
  comp_name: Joi.string().optional(),
  email: Joi.string().email().optional(),
  fcmtoken: Joi.string().optional().allow(null).allow(""),
  lat: Joi.number().optional(),
  lng: Joi.number().optional(),
  address: Joi.string().optional(),
  // status: Joi.string().optional().default("active"),
  radius: Joi.number().optional().allow(null).allow(""),
  driving_license: Joi.string().allow(null, "").optional(),
  type: Joi.string().optional(),
  role: Joi.string().optional(),
  access_types: Joi.string().optional().allow(null, ""),
  // Operator can upload insurance without full junk signup (accept-gate flow).
  isInsured: Joi.boolean().optional(),
  insuranceFile: Joi.string().allow(null, "").optional(),
  // .valid("portaPotty", "treeRemoval", "junkRemoval", "company"),
  company: Joi.object({
    companyName: Joi.string().optional(),
    legalBusinessName: Joi.string().optional(),
    email: Joi.string().email().optional(),
    address: Joi.string().optional().allow("", null),
    city: Joi.string().optional().allow("", null),
    state: Joi.string().optional().allow("", null),
    zip: Joi.string().optional().allow(null, ""),
    country: Joi.string().optional().allow("", null),
    phone: Joi.string().optional().allow(null, ""),
    // Optional — commercial signup no longer requires a map/address step.
    location: Joi.object({
      type: Joi.string().valid("Point").required(),
      coordinates: Joi.array().items(Joi.number()).length(2).required(),
    }).optional(),
    COI: Joi.string().allow("", null).optional(),
    W9: Joi.string().allow("", null).optional(),
    logo: Joi.string().allow("", null).optional(),
    EIN: Joi.string().optional().allow("", null),
    primaryContact: Joi.object({
      name: Joi.string().required(),
      email: Joi.string().email().optional().allow("", null),
      phone: Joi.string().optional().allow("", null),
      title: Joi.string().required(),
    }).optional(),
    accountsPayableEmail: Joi.string().email().allow("", null).optional(),
    expectedMonthlyVolume: Joi.number().allow("", null).optional(),
    PO: Joi.boolean().optional(),
    taxExempt: Joi.string().allow("", null).optional(),
    authorizedSigner: Joi.object({
      name: Joi.string().required(),
      email: Joi.string().email().optional().allow("", null),
      phone: Joi.string().optional().allow("", null),
      title: Joi.string().required(),
    }).optional(),
    dba: Joi.string().optional().allow("", null),
    status: Joi.string().optional().allow("", null),
  }).optional(),
  junkRemoval: Joi.object({
    companyName: Joi.string().required(),
    legalBusinessName: Joi.string().required(),
    sameDayAvailable: Joi.boolean().required(),
    ein: Joi.string().optional().allow(null, ""),
    ownerFullName: Joi.string().optional().allow(null, ""),
    address: Joi.string().optional().allow(null, ""),
    city: Joi.string().optional().allow(null, ""),
    state: Joi.string().optional().allow(null, ""),
    zip: Joi.string().optional().allow(null, ""),
    country: Joi.string().optional().allow(null, ""),
    phone: Joi.string().optional().allow(null, ""),
    location: Joi.object({
      type: Joi.string().valid("Point").required(),
      coordinates: Joi.array().items(Joi.number()).length(2).required(),
    }).required(),
    drivers_license: Joi.array().items(Joi.string()).optional(),
    COI: Joi.string().optional().allow(null, ""),
    insurance_expiry_date: Joi.date().optional().allow(null, ""),
    insuranceExpiryDate: Joi.date().optional().allow(null, ""),
    radius: Joi.number().optional().allow(null).allow(""),
    Business_license: Joi.string().optional().allow(null, ""),
    minimum_insurance_amount: Joi.string().optional().allow(null, ""),
  }).optional(),
  treeRemoval: Joi.object({
    companyName: Joi.string().required(),
    legalBusinessName: Joi.string().required(),
    sameDayAvailable: Joi.boolean().required(),
    ownerFullName: Joi.string().optional().allow(null, ""),
    address: Joi.string().optional().allow(null, ""),
    city: Joi.string().optional().allow(null, ""),
    state: Joi.string().optional().allow(null, ""),
    zip: Joi.string().optional().allow(null, ""),
    country: Joi.string().optional().allow(null, ""),
    phone: Joi.string().optional().allow(null, ""),
    location: Joi.object({
      type: Joi.string().valid("Point").required(),
      coordinates: Joi.array().items(Joi.number()).length(2).required(),
    }).required(),
    ein: Joi.string().optional().allow(null, ""),
    drivers_license: Joi.array().items(Joi.string()).optional(),
    COI: Joi.string().optional().allow(null, ""),
    radius: Joi.number().optional().allow(null).allow(""),
    License_Type: Joi.string().optional().allow(null, ""),
    License_Number: Joi.string().optional().allow(null, ""),
    License_State: Joi.string().optional().allow(null, ""),
    License_Expiration: Joi.date().optional().allow(null, ""),
    Tree_removal_license: Joi.string().optional().allow(null, ""),
    Workers_comp: Joi.string().optional().allow(null, ""),
    Certified_arborist: Joi.boolean().optional(),
    Arborist_credential: Joi.string().optional().allow(null, ""),
  }).optional(),
});
